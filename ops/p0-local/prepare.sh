#!/usr/bin/env bash
# MC-P0-ZCODE-EXECUTION — local ZITADEL profile preparation (idempotent-safe: refuses overwrite).
# Generates task-owned runtime secrets into ops/p0-local/secrets (0600) and writes
# ops/p0-local/.env + ops/p0-local/config/zitadel-config.yaml.
# No sample credentials from documentation are used. Public material only in config.
set -euo pipefail
export LC_ALL=C
cd "$(dirname "$0")"

for cmd in openssl python3 shasum; do command -v "$cmd" >/dev/null || { echo "missing $cmd" >&2; exit 1; }; done

mkdir -p secrets config runtime
chmod 700 secrets runtime
umask 077

if [ -e .env ]; then echo "REFUSING: ops/p0-local/.env already exists (instance already prepared)" >&2; exit 2; fi

MASTERKEY="$(openssl rand -hex 16)"
DBPASS="$(openssl rand -hex 16)"
COOKIE="$(openssl rand -base64 32)"
ADMINPW="Aa1!$(openssl rand -hex 10)"

openssl genrsa -traditional -out secrets/system-user.pem 2048 2>/dev/null
openssl rsa -in secrets/system-user.pem -outform PEM -pubout -out secrets/system-user.pub 2>/dev/null
PUB64="$(openssl base64 -A -in secrets/system-user.pub)"

printf '%s' "$MASTERKEY" > secrets/masterkey.txt
printf '%s' "$DBPASS"   > secrets/db-password.txt
printf '%s' "$ADMINPW"  > secrets/admin-password.txt
printf '%s' "$COOKIE"   > secrets/login-cookie-secret.txt
chmod 600 secrets/*

cat > .env <<EOF
# Generated by prepare.sh $(date -u +%Y-%m-%dT%H:%M:%SZ) — task-owned local profile (0600).
ZITADEL_VERSION=v4.16.0
TRAEFIK_IMAGE=traefik:v3.7.7
POSTGRES_IMAGE=postgres:17.10-alpine
ZITADEL_DOMAIN=localhost
PROXY_HTTP_PUBLISHED_PORT=8080
ZITADEL_EXTERNALPORT=8080
ZITADEL_EXTERNALSECURE=false
ZITADEL_PUBLIC_SCHEME=http
ZITADEL_MASTERKEY=$MASTERKEY
ZITADEL_FIRSTINSTANCE_ORG_HUMAN_PASSWORD=$ADMINPW
ZITADEL_FIRSTINSTANCE_ORG_HUMAN_PASSWORDCHANGEREQUIRED=false
ZITADEL_DATABASE_POSTGRES_DSN=postgresql://postgres:$DBPASS@postgres:5432/zitadel?sslmode=disable
POSTGRES_DB=zitadel
POSTGRES_ADMIN_USER=postgres
POSTGRES_ADMIN_PASSWORD=$DBPASS
LOGIN_SESSION_COOKIE_SECRET=$COOKIE
LOGIN_CLIENT_PAT_EXPIRATION=2099-01-01T00:00:00Z
ZITADEL_ACCESS_LOG_STDOUT_ENABLED=true
TRAEFIK_DASHBOARD_ENABLED=false
TRAEFIK_LOG_LEVEL=WARN
TRAEFIK_ACCESSLOG_ENABLED=false
EOF
chmod 600 .env

cat > config/zitadel-config.yaml <<EOF
# Public-key material only. Private key: secrets/system-user.pem (0600).
# Note: FirstInstance.Org.Machine cannot be provisioned from env or --config (the
# FirstInstance step config is loaded from a separate steps viper fed by the
# --steps flag, which start-from-init does not expose); provisioning automation
# therefore uses the bootstrap login-client PAT -> admin human session route
# (see provision.sh). This SystemAPIUsers entry remains for instance-level
# operational reads only.
SystemAPIUsers:
  - mc-bootstrap:
      KeyData: $PUB64
      Memberships:
        - MemberType: System
          Roles:
            - "SYSTEM_OWNER"
            - "IAM_OWNER"
            - "ORG_OWNER"
EOF
chmod 600 config/zitadel-config.yaml

echo "PREPARED: secrets/ .env config/zitadel-config.yaml written (0600). Next: docker compose up -d --wait"
